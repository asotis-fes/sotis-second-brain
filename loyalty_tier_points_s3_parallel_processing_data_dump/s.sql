
USE WAREHOUSE FDE_DEVELOPER_3XL_WH;

-- 1000 random effective loyalty ids that HAVE ledger history (so all 3 files populate) ------
CREATE OR REPLACE TRANSIENT TABLE FES_USERS.ALEX_SOTIS.TP_SAMPLE_ACCOUNTS AS
SELECT loyalty_account_id
FROM (SELECT DISTINCT loyalty_account_id FROM FES_USERS.ALEX_SOTIS.TP_LEDGER_SNAPSHOT)
ORDER BY RANDOM() LIMIT 1000;

-- restrict the de-collide snapshot to the sample (FMTI + overrides JOIN EFF_SNAP -> sample only)
CREATE OR REPLACE TRANSIENT TABLE FES_USERS.ALEX_SOTIS.TP_EFF_SAMPLE AS
SELECT * FROM FES_USERS.ALEX_SOTIS.TP_EFFECTIVE_SNAPSHOT
WHERE effective_loyalty_id IN (SELECT loyalty_account_id FROM FES_USERS.ALEX_SOTIS.TP_SAMPLE_ACCOUNTS);
CREATE OR REPLACE TRANSIENT TABLE FES_USERS.ALEX_SOTIS.TP_EFFECTIVE_SNAPSHOT AS SELECT * FROM FES_USERS.ALEX_SOTIS.TP_EFF_SAMPLE;

-- restrict + re-chunk the ledger snapshot to the sample (fresh chunk_num -> all in chunk 0)
CREATE OR REPLACE TRANSIENT TABLE FES_USERS.ALEX_SOTIS.TP_LEDGER_SAMPLE AS
WITH s AS (
    SELECT * FROM FES_USERS.ALEX_SOTIS.TP_LEDGER_SNAPSHOT
    WHERE loyalty_account_id IN (SELECT loyalty_account_id FROM FES_USERS.ALEX_SOTIS.TP_SAMPLE_ACCOUNTS)
),
r AS (
    SELECT loyalty_account_id,
           FLOOR((DENSE_RANK() OVER (ORDER BY loyalty_account_id) - 1) / 200000) AS chunk_num
    FROM (SELECT DISTINCT loyalty_account_id FROM s)
)
SELECT s.* EXCLUDE (chunk_num), r.chunk_num
FROM s JOIN r USING (loyalty_account_id);
CREATE OR REPLACE TRANSIENT TABLE FES_USERS.ALEX_SOTIS.TP_LEDGER_SNAPSHOT AS SELECT * FROM FES_USERS.ALEX_SOTIS.TP_LEDGER_SAMPLE;

DROP TABLE IF EXISTS FES_USERS.ALEX_SOTIS.TP_EFF_SAMPLE;
DROP TABLE IF EXISTS FES_USERS.ALEX_SOTIS.TP_LEDGER_SAMPLE;

